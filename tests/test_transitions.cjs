const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {replacement}=require('../web/message-transitions.js');
const root=path.resolve(__dirname,'..');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/catalog.json'),'utf8'));
catalog.message_transitions=JSON.parse(fs.readFileSync(path.join(root,'data/message-transitions.json'),'utf8'));
assert.equal(replacement('109',catalog,'prod').current,'10910');
assert.equal(replacement('109',catalog,'test').current,'10910');
assert.equal(replacement('101',catalog).current,'10110');
assert.equal(replacement('109',catalog).production_retired_at,'2026-09-19T10:00:00+03:00');
assert.equal(replacement('10910',catalog),null,'a new message is a distinct type');
assert.equal(replacement('110',catalog),null,'suffix match alone cannot establish replacement');
assert.equal(replacement('104',catalog),null,'do not extend the dated notice to unlisted messages');
assert.equal(replacement('999',catalog),null);
const missing={...catalog,revisions:catalog.revisions.filter(r=>r.number!=='10910'),registry:catalog.registry.filter(r=>r.number!=='10910')};
assert.equal(replacement('109',missing),null,'never create a broken replacement link');
const testOnly={...catalog,revisions:catalog.revisions.filter(r=>r.number!=='10910'||r.environment==='test'),registry:catalog.registry.filter(r=>r.number!=='10910'||r.environment==='test')};
assert.equal(replacement('109',testOnly,'prod'),null,'keep contour scope');
assert.equal(replacement('109',testOnly,'test').current,'10910');
assert.equal(replacement('109',{...catalog,message_transitions:undefined}),null);
for(const pair of catalog.message_transitions.pairs)assert.equal(replacement(pair.previous,catalog).current,pair.current);
console.log('ECP transitions verified: confirmed ten types, production date, contour scope, no guessed or missing replacements.');
