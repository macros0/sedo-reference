const assert=require('node:assert/strict');
const {journalDateRange,journalDateMatches}=require('../web/journal.js');
assert.equal(typeof journalDateRange,'function','journal date range API exists');
const now=new Date('2026-11-12T12:00:00Z');
const week=journalDateRange('week','','',now);
assert.equal(week.from,'2026-11-06');assert.equal(week.to,'2026-11-12');
assert.equal(journalDateMatches('2026-11-05T21:00:00Z',week),true,'start is midnight Moscow');
assert.equal(journalDateMatches('2026-11-05T20:59:59Z',week),false);
assert.equal(journalDateMatches('2026-11-12T20:59:59.999Z',week),true,'whole final day included');
assert.equal(journalDateMatches('2026-11-12T21:00:00Z',week),false);
const afterMidnight=journalDateRange('week','','',new Date('2026-11-12T21:01:00Z'));
assert.equal(afterMidnight.to,'2026-11-13','today follows Moscow, not UTC');
assert.equal(afterMidnight.from,'2026-11-07');
assert.equal(journalDateRange('week','','',new Date('2027-01-01T12:00:00Z')).from,'2026-12-26');
assert.equal(journalDateRange('month','','',new Date('2026-03-01T12:00:00Z')).from,'2026-01-31');
assert.equal(journalDateRange('month','','',new Date('2024-03-01T12:00:00Z')).from,'2024-02-01');
const custom=journalDateRange('custom','2026-11-12','2026-11-12',now);
assert.equal(journalDateMatches('2026-11-11T21:00:00Z',custom),true);
assert.equal(journalDateMatches('2026-11-12T20:59:59Z',custom),true);
assert.equal(journalDateMatches('2026-11-12T21:00:00Z',custom),false);
assert.equal(journalDateMatches('2026-11-20T12:00:00Z',journalDateRange('custom','2026-11-12','',now)),true);
assert.equal(journalDateMatches('2026-11-01T12:00:00Z',journalDateRange('custom','','2026-11-12',now)),true);
assert.ok(journalDateRange('custom','2026-11-13','2026-11-12',now).error);
assert.ok(journalDateRange('custom','2026-02-29','',now).error,'reject invalid calendar date');
assert.ok(journalDateRange('custom','bad-date','',now).error);
assert.equal(journalDateMatches(null,week),false);
assert.equal(journalDateMatches('invalid',week),false);
assert.equal(journalDateMatches(null,journalDateRange('all','','',now)),true,'unknown dates visible without date filter');
assert.equal(journalDateMatches('2026-11-12T12:00:00Z',journalDateRange('custom','2026-11-13','2026-11-12',now)),false);
console.log('Journal date filters verified: Moscow boundaries, inclusive days, 7/30 days, leap years, open intervals and invalid input.');
